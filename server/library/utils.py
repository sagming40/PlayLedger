# normalize_title 함수의 한계
#
# 가-힣 ─ 완성형 한글만 커버한다. 자모가 분리된 글자는 지워짐 (예: ㅅㅏ → ㅅ + ㅏ)
# "사이버펑크2077"과 "cyberpunk2077"은 정규화를 한다 하더라도 엄연히 다른 값이다.
# 따라서, ERD에 별칭 테이블이 필요하지만 MVP 범위에서는 다루지 않는다. ─ 이미 알고 있는 한계

import re


def normalize_title(title: str) -> str:
    """
    제목을 '비교 전용 문자열'로 바꾼다.
    
    비유: 옷에 붙은 세탁 라벨
    사람이 확인하는 것 ─ 옷 디자인(title).
    기계가 확인하는 것 ─ 라벨(title_norm). "이게 같은 옷인지" 판단할 때
    라벨은 예쁠 필요가 없다. 비교 역할만 잘 수행하면 됨
    """
    # 1) 앞뒤 공백을 털어내고 전부 소문자로
    #    "Cyberpunk 2077" / "CYBERPUNK 2077" → 여기서 같아진다
    s = title.strip().lower()
    
    # 2) 한글·영문·숫자만 남기고 나머지는 전부 제거
    #    공백, 콜론(:), 하이픈(-), 느낌표(!), 물결(~)... 표기 흔들림의 주범들
    #    "사이버펑크 2077" → "사이버펑크2077"
    #    "Marvel's Spider-Man" → "marvelsspiderman"
    #
    #    \w를 사용하지 않는 이유: \w는 밑줄(_)도 포함하고 유니코드 범위가 넓다.
    #    따라서, "뭐가 남고 뭐가 지워지는지"가 눈에 보이지 않는다. 직접 범위를 적는 것이 예측하기 수월함.
    s = re.sub(r"[^0-9a-z가-힣]", "", s)
    
    return s
